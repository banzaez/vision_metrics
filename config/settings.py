from .app_config import AppConfig
from .sections.system import SystemConfig, PerformanceConfig, UIConfig
from .sections.yolo import YOLOParams, YOLOModel, YOLOImageSize
from .sections.tracker import TrackerConfig, TrackerType, ReIDModel
from .sections.reid import CustomReIDConfig

# =============================================================================
# ГЛАВНЫЙ ФАЙЛ НАСТРОЕК (VISION METRICS)
# =============================================================================
# Основной пульт управления системой. 
# Изменения здесь влияют на баланс Скорость / Точность.
# =============================================================================

settings = AppConfig(
    # --- СИСТЕМНЫЕ НАСТРОЙКИ (ЖЕЛЕЗО И ПРОИЗВОДИТЕЛЬНОСТЬ) ---
    system=SystemConfig(
        perf=PerformanceConfig(
            # 'mps' — ускорение на чипах Apple M. 'cuda' — для NVIDIA. 'cpu' — для процессора.
            device='auto', 
            
            # FP16 (половинная точность). Включать ОБЯЗАТЕЛЬНО для Apple Silicon.
            # Ускоряет инференс в ~2 раза почти без потери точности.
            half=True,
            
            # Batch=1 — критично для минимизации задержки (latency) в реальном времени.
            batch_size=1,
            
            # frame_rate: Ожидаемая скорость видео. Помогает трекеру предсказывать движение.
            frame_rate=25,
            
            # frame_interval: Главный рычаг скорости.
            # 1 — обрабатываем каждый кадр (макс. точность).
            # 3 — обрабатываем каждый 3-й кадр (в 3 раза быстрее, но трекинг может "дребезжать").
            frame_interval=3,
            
            # Количество ядер CPU, выделенных на чтение видеопотока.
            opencv_threads=4
        ),
        ui=UIConfig(
            # На сколько кадров прыгаем при нажатии стрелок в плеере.
            step_frames=125,
            
            # Вывод технической инфы (FPS, Mem) поверх видео. Полезно для отладки.
            show_monitoring=True
        ),
        # Список источников. Можно комбинировать файлы и ссылки на IP-камеры.
        video_sources=[
            './data/videos/Camera_01_10.12.0.35_10.12.0.235_20260401113050_20260401113550_3084159.mp4'
        ]
    ),

    # --- НАСТРОЙКИ НЕЙРОСЕТИ (ДЕТЕКЦИЯ YOLO) ---
    yolo=YOLOParams(
        path_to_models="./data/models/",
        
        # Выбор весов. YOLO26S — легкая и быстрая. YOLO26L — тяжелая, но видит мелкие детали.
        weights="./data/models/" + YOLOModel.YOLO26S.value,
        
        # imgsz: Размер "зрения" нейросети. 
        # Чем выше (L/XL), тем лучше видит людей вдали, но тем ниже FPS.
        # Для ювелирки (камеры близко) M.value (960) — идеальный баланс.
        imgsz=YOLOImageSize.M.value,
        
        # conf_threshold: "Сито" для объектов. 
        # < 0.25 — много ложных срабатываний (принимает тени за людей).
        # > 0.50 — пропускает людей со спины или в капюшонах.
        conf_threshold=0.30,
        
        # iou_threshold: Порог склеивания дубликатов рамок. 
        # Ниже 0.45 — может принять одного человека за двух.
        iou_threshold=0.5,
        
        # agnostic_nms: Если True, не позволит рамкам разных классов накладываться.
        # Для ритейла лучше False (человек может нести сумку/коробку).
        agnostic_nms=False,
        
        # retina_masks: Высокое разрешение масок сегментации. 
        # Ставить True только если нужно ИДЕАЛЬНО обводить силуэт для аналитики касаний.
        retina_masks=False
    ),

    # --- НАСТРОЙКИ ТРЕКЕРА (УДЕРЖАНИЕ ID) ---
    tracker=TrackerConfig(
        # HYBRIDSORT / BOTSORT — лучшие для ювелирки (учитывают и движение, и внешность).
        type=TrackerType.HYBRIDSORT,
        
        # Включает использование Re-ID модели для распознавания лиц/одежды.
        with_reid=True,
        
        # Выбор "мозга" для Re-ID. 
        # OSNET_X1_0 — стандарт. OSNET_AIN — если много бликов от витрин.
        reid_model=ReIDModel.OSNET_X1_0,
        
        # Классы: 0 — это 'person' в COCO датасете.
        classes=[0],
        
        # КАСТОМНАЯ СШИВКА (RE-ID GALLERY) НАШИ ЭКСПЕРИМЕНТЫ
        # Позволяет узнать человека, если он вышел из кадра и вернулся под новым ID.
        custom_reid=CustomReIDConfig(
            # Включите, если ID часто "прыгают" при заходе за прилавки.
            enabled=False,
            
            # threshold: Насколько человек должен быть похож на "умерший" ID (0.0-1.0).
            # 0.6-0.7 — оптимально. 0.9 — слишком строго, никого не узнает.
            threshold=0.6,
            
            # Сколько "ушедших" людей хранить в памяти (dead_pool).
            gallery_size=100,
            
            # ema_alpha: Скорость обновления "портрета" человека.
            # 0.6 — быстро привыкает к новому освещению.
            ema_alpha=0.6,
            
            # Как часто слать отчеты о склейках в интерфейс (в кадрах).
            stats_callback_interval=15
        )
    )
)

# Загрузка ROI (зон интереса) и масок игнорирования.
settings.load()