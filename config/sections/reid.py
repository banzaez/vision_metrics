from dataclasses import dataclass


# ==> SETTINGS CUSTOM REID


@dataclass
class CustomReIDConfig:
    """Конфигурация кастомного алгоритма сшивки треков (CustomReIDStitcher)."""

    enabled: bool = False
    """Включение/выключение кастомной сшивки."""

    threshold: float = 0.6
    """Порог уверенности для принятия решения о сшивке (0.0 - 1.0)."""

    gallery_size: int = 100
    """Максимальное количество треков, хранимых в галерее для сшивки."""

    ema_alpha: float = 0.6
    """Коэффициент сглаживания (EMA) для обновления эмбеддингов в галерее (0.0 - 1.0).
    Более высокое значение сохраняет историю, более низкое — быстрее адаптируется к изменениям освещения."""

    stats_callback_interval: int = 15
    """Как часто (в кадрах) отправлять в UI полные списки ID галереи и dead pool.
    0 — каждый кадр (как раньше). Между полными обновлениями уходят только счётчики."""
